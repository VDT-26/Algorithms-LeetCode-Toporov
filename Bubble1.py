def bubble_sort(arr):
    # Получаем длину списка
    n = len(arr)

    # Внешний цикл — количество проходов по списку
    for i in range(n):
        # Флаг, который покажет, были ли обмены на этом проходе
        swapped = False

        # Внутренний цикл — сравниваем пары элементов
        # Каждый раз можно идти на один элемент меньше (n - i - 1),
        # потому что последние i элементов уже стоят на своих местах
        for j in range(0, n - i - 1):

            # Если текущий элемент больше следующего — меняем их местами
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True  # фиксируем, что был обмен

        # Если за весь проход не было ни одного обмена —
        # значит массив уже отсортирован, можно завершать раньше
        if not swapped:
            break

    # Возвращаем отсортированный список
    return arr


# --- пользовательский ввод ---
# Пользователь вводит строку чисел через пробел
raw = input("Введите числа через пробел: ")

# split() разбивает строку на части, map(int, ...) превращает их в числа
data = list(map(int, raw.split()))

# Вывод результата
print("Отсортированный список:", bubble_sort(data))
