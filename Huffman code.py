# Импортируем heapq для работы с приоритетной очередью (минимальная куча)
import heapq
# Импортируем Counter для подсчета количества повторений каждого символа
from collections import Counter

# Класс Node представляет узел дерева Хаффмана
class Node:
    # Конструктор инициализирует узел
    def __init__(self, char, freq):
        self.char = char      # Символ, хранящийся в узле (None для внутренних узлов)
        self.freq = freq      # Частота (вес) узла
        self.left = None      # Левое поддерево
        self.right = None     # Правое поддерево

    # Метод сравнения для сортировки узлов в куче по частоте
    def __lt__(self, other):
        return self.freq < other.freq

# Функция строит дерево Хаффмана из входного текста
def build_huffman_tree(text):
    # Подсчитываем количество каждого символа в тексте
    count = Counter(text)
    
    # Создаем список узлов, по одному для каждого уникального символа
    heap = [Node(char, freq) for char, freq in count.items()]
    
    # Преобразуем список в минимальную кучу
    heapq.heapify(heap)

    # Строим дерево снизу вверх, пока в куче не останется один узел (корень)
    while len(heap) > 1:
        # Извлекаем два узла с наименьшей частотой
        left = heapq.heappop(heap)
        right = heapq.heappop(heap)
        
        # Создаем новый внутренний узел с суммой частот двух узлов
        merged = Node(None, left.freq + right.freq)
        
        # Присваиваем извлеченные узлы как потомков нового узла
        merged.left = left
        merged.right = right
        
        # Добавляем новый узел обратно в кучу
        heapq.heappush(heap, merged)

    # Возвращаем корень дерева (последний оставшийся узел в куче)
    return heap[0]

# Функция генерирует коды Хаффмана путем обхода дерева
def generate_codes(node, prefix="", codes=None):
    # При первом вызове инициализируем словарь для хранения кодов
    if codes is None:
        codes = {}
    
    # Если узел - листовой (содержит символ)
    if node.char is not None:
        # Сохраняем код для этого символа (путь от корня до листа)
        codes[node.char] = prefix
    else:
        # Если внутренний узел, рекурсивно обходим потомков
        # Для левого поддерева добавляем "0" к коду
        generate_codes(node.left, prefix + "0", codes)
        # Для правого поддерева добавляем "1" к коду
        generate_codes(node.right, prefix + "1", codes)
    
    # Возвращаем словарь с кодами для всех символов
    return codes

# Функция кодирует текст с помощью кодов Хаффмана
def huffman_encode(text):
    # Строим дерево Хаффмана из входного текста
    root = build_huffman_tree(text)
    
    # Генерируем коды для каждого символа
    codes = generate_codes(root)
    
    # Заменяем каждый символ на его код и соединяем в одну строку
    encoded = "".join(codes[char] for char in text)
    
    # Возвращаем закодированный текст и дерево (нужно для декодирования)
    return encoded, root

# Функция декодирует бинарную строку обратно в исходный текст
def huffman_decode(encoded, root):
    # Список для хранения декодированных символов
    decoded = []
    
    # Начинаем с корня дерева
    node = root
    
    # Проходим по каждому биту в закодированной строке
    for bit in encoded:
        # Если бит "0", идем в левое поддерево; если "1", идем в правое
        node = node.left if bit == '0' else node.right
        
        # Если достигли листового узла (содержит символ)
        if node.char is not None:
            # Добавляем символ в результат
            decoded.append(node.char)
            # Возвращаемся к корню для декодирования следующего символа
            node = root
    
    # Объединяем все символы в строку и возвращаем результат
    return "".join(decoded)

# Переменная для хранения дерева между операциями кодирования и декодирования
saved_tree = None

# Главный цикл программы для взаимодействия с пользователем
while True:
    # Запрашиваем у пользователя выбор действия
    choice = input("1-код, 2-декод, 3-выход: ")
    
    # Если пользователь выберет 1, кодируем текст
    if choice == '1':
        # Получаем текст от пользователя
        text = input("Текст: ")
        
        # Кодируем текст и сохраняем дерево для последующего декодирования
        encoded, saved_tree = huffman_encode(text)
        
        # Генерируем коды символов для информации пользователю
        codes = generate_codes(saved_tree)
        
        # Выводим закодированный текст
        print(f"Результат: {encoded}")
        
        # Выводим словарь кодов
        print(f"Коды: {codes}\n")
    
    # Если пользователь выберет 2, декодируем текст
    elif choice == '2':
        # Проверяем, есть ли сохраненное дерево (т.е. был ли текст закодирован ранее)
        if saved_tree:
            # Получаем закодированную строку от пользователя
            encoded = input("Строка 0 и 1: ")
            
            # Декодируем строку с помощью сохраненного дерева
            decoded = huffman_decode(encoded, saved_tree)
            
            # Выводим декодированный текст
            print(f"Результат: {decoded}\n")
        else:
            # Напоминаем пользователю, что нужно сначала закодировать текст
            print("Сначала закодируй текст\n")
    
    # Если пользователь выберет 3, завершаем программу
    elif choice == '3':
        break